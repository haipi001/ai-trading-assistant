assert.equal(selectMarketAsset(sameVenue,'BTC','币安','USDT').id,2);
assert.throws(()=>selectMarketAsset(sameVenue,'BTCUSD','币安','USDT'));
assert.throws(()=>selectMarketAsset([{id:1,symbol:'BTC',venue:'binance',currency:'USD'}],'BTC','币安','USDT'));
assert.throws(()=>selectMarketAsset([{id:1,symbol:'BTCUSDT',venue:'binance',currency:'USD'}],'BTC','币安','USDT'));
assert.throws(()=>selectMarketAsset([{id:1,symbol:'BTC',venue:'binance'}],'BTC','币安','USDT'));
assert.equal(selectMarketAsset([{id:1,symbol:'BTC',venue:'binance',currency:'USDT'}],'BTC','币安','USDT').id,1);
assert.throws(()=>selectMarketAsset([{id:1,symbol:'BTC',venue:'binance',currency:'USDT'},sameVenue[1]],'BTC','币安','USDT'));
assert.equal(selectMarketAsset([{id:1,symbol:'AAPL',venue:'NASDAQ',currency:'USD'}],'AAPL','NASDAQ','USD').id,1);
const strictCalls=[];
const strict=await loadBackendCandles('BTC','5m',{venue:'币安',quoteCurrency:'USDT',request:async path=>{strictCalls.push(path);return path.startsWith('/assets')?sameVenue:[{asset_id:2,timeframe:'5m',timestamp:'2026-10-28T00:00:00Z',open:10,high:12,low:9,close:11,volume:1,source:'fixture'}]}});
assert.equal(strict.status,'connected');assert.equal(strict.asset.id,2);assert.equal(strict.quoteCurrency,'USDT');assert.match(strictCalls[1],/asset_id=2&timeframe=5m/);
let candleRequests=0;const missing=await loadBackendCandles('BTC','5m',{venue:'币安',quoteCurrency:'USDT',request:async path=>{if(!path.startsWith('/assets'))candleRequests++;return [sameVenue[0]];}});assert.equal(missing.status,'missing');assert.equal(candleRequests,0);
for(const status of [401,403]){const unauthorized=await loadBackendCandles('BTC','5m',{request:async()=>{throw Object.assign(new Error('API '+status),{status});}});assert.equal(unauthorized.status,'unauthorized');assert.match(unauthorized.source,new RegExp(String(status)));assert.equal(unauthorized.candles.length,0);}
const crossOrigin=await loadBackendCandles('BTC','5m',{request:async()=>{throw new TypeError('Failed to fetch');}});assert.equal(crossOrigin.status,'offline');assert.match(crossOrigin.source,/跨域/);
const serverError=await loadBackendCandles('BTC','5m',{request:async()=>{throw Object.assign(new Error('API500'),{status:500});}});assert.equal(serverError.status,'error');assert.match(serverError.source,/500/);
let options=['十字光标','周期','日期范围'];const calls=[];
const sync=createChartSync(()=>options);
sync.register(0,{crosshair(){},timeRange(){},zoom(){}});
const cleanup=sync.register(1,{crosshair:time=>{calls.push(['crosshair',time]);sync.crosshair(1,time)},timeRange:range=>{calls.push(['date',range]);sync.range(1,{from:0,to:10},range)},zoom:span=>calls.push(['zoom',span])});
sync.crosshair(0,123);assert.deepEqual(calls,[['crosshair',123]]);
sync.range(0,{from:0,to:20},{from:100,to:200});assert.equal(calls.at(-1)[0],'date');
options=['缩放比例'];sync.range(0,{from:0,to:50},null);assert.deepEqual(calls.at(-1),['zoom',50]);
cleanup();const count=calls.length;sync.crosshair(0,999);assert.equal(calls.length,count);
console.log('Market periods, validated feeds, venue matching and reentrant sync checks passed');

