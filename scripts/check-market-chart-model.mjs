let preciseCalls=[];const precise=createChartSync(()=>['周期','日期范围']);
precise.register(0,{timeline:'100,200',crosshair(){},timeRange(){},logicalRange(){}});
precise.register(1,{timeline:'100,200',crosshair(){},timeRange:range=>preciseCalls.push(['date',range]),logicalRange:range=>preciseCalls.push(['logical',range])});
precise.register(2,{timeline:'100,300',crosshair(){},timeRange:range=>preciseCalls.push(['otherDate',range])});
precise.range(0,{from:.7,to:1.8},{from:100,to:200});
assert.deepEqual(preciseCalls,[['logical',{from:.7,to:1.8}],['otherDate',{from:100,to:200}]]);
precise.range(1,{from:.7,to:1.8},{from:100,to:200});assert.equal(preciseCalls.length,2);
console.log('Identical timelines preserve fractional logical ranges; distinct timelines retain date sync');
