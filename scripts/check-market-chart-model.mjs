import assert from 'node:assert/strict';
import { periodDefinition, periodBounds, periodCountdown, demoMarketBars, validateMarketBars, selectMarketAsset, createChartSync } from '../src/market-chart-model.js';
import { loadBackendCandles } from '../src/market-api.js';
assert.equal(periodDefinition('分时').timeframe,'1m');
assert.equal(periodDefinition('45分').seconds,2700);
for(const invalid of ['0分','-1日','1.5时','未知']) assert.throws(()=>periodDefinition(invalid));
const now=Date.UTC(2026,9,28,0,3,10);
assert.equal(periodCountdown('5分',now),'00:01:50');
assert.equal(periodBounds('季K',now).end,Date.UTC(2027,0,1)/1000);
assert.equal(periodBounds('1周',now).start,Date.UTC(2026,9,26)/1000);
const bars=demoMarketBars(100,'5分','BTC:币安',now);
assert.equal(bars.at(-1).close,100);
assert.deepEqual(validateMarketBars(bars),bars);
assert.throws(()=>validateMarketBars([bars[0],bars[0]]));
assert.throws(()=>validateMarketBars([{...bars[0],high:0}]));
const assets=[{id:1,symbol:'BTCUSDT',venue:'binance'},{id:2,symbol:'BTCUSD',venue:'coinbase'}];
assert.equal(selectMarketAsset(assets,'BTC','币安').id,1);
assert.throws(()=>selectMarketAsset(assets,'BTC'));
assert.throws(()=>selectMarketAsset(assets,'BTCUSD','币安'));
const requests=[];
const result=await loadBackendCandles('BTC','5m',{venue:'币安',request:async path=>{requests.push(path);return path.startsWith('/assets')?assets:[{asset_id:1,timeframe:'5m',timestamp:'2026-10-28T00:00:00Z',open:10,high:12,low:9,close:11,volume:1,source:'fixture'}]}});
assert.equal(result.status,'connected');assert.match(requests[1],/asset_id=1&timeframe=5m/);
const invalid=await loadBackendCandles('BTC','5m',{venue:'币安',request:async path=>path.startsWith('/assets')?assets:[{asset_id:2,timeframe:'5m'}]});
assert.equal(invalid.status,'invalid');assert.equal(invalid.candles.length,0);
