import assert from 'node:assert/strict';
import {validateViewport,viewportRange,zoomLogicalRange,validLogicalRange} from '../src/chart-viewport.js';
import {captureChartLayout,validateChartLayout} from '../src/chart-layout-state.js';
const view={key:'BTC:币安:5分:full',logical:{from:10,to:60},first:100,last:200,timeRange:{from:120,to:180}};
assert.deepEqual(viewportRange(view,view.key,[{time:100},{time:200}]),{logical:view.logical});
assert.deepEqual(viewportRange(view,view.key,[{time:110},{time:210}]),{time:view.timeRange});
assert.equal(viewportRange(view,'ETH:币安:5分:full',[{time:100},{time:200}]),null);
assert.equal(viewportRange(view,view.key,[{time:300},{time:400}]),null);
assert.deepEqual(zoomLogicalRange({from:0,to:100},.7),{from:30,to:100});
assert.equal(validLogicalRange({from:NaN,to:1}),false);
assert.throws(()=>validateViewport({...view,logical:{from:20,to:10}}));
assert.throws(()=>validateViewport({...view,timeRange:{from:0,to:1}}));
const state={marketMode:'web3',symbol:'BTC',venue:'币安',period:'5分',chartType:'蜡烛图',paneCount:2,paneSync:[],studies:[],paneSymbols:[],panePeriods:[],paneStudies:[],viewports:{0:view}};
const saved=captureChartLayout(state);view.logical.from=20;assert.equal(saved.viewports[0].logical.from,10);
assert.deepEqual(validateChartLayout(JSON.parse(JSON.stringify(saved))),saved);
assert.throws(()=>validateChartLayout({...saved,viewports:{18:saved.viewports[0]}}));
console.log('Viewport checks: logical/date restoration, identity isolation, zoom bounds, corruption and immutable layout roundtrip passed');

