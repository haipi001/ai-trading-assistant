import assert from 'node:assert/strict';
import {gridTemplate,validateGridGeometry} from '../src/chart-grid-geometry.js';
import {captureChartLayout,validateChartLayout} from '../src/chart-layout-state.js';
assert.equal(gridTemplate(2,{columns:2,weights:[4,1]}),'minmax(0,4fr) minmax(0,1fr)');
assert.equal(gridTemplate(1,{columns:2,weights:[4,1]}),'minmax(0,4fr)');
for(const invalid of [{columns:7,weights:[]},{columns:2,weights:[1]},{columns:1,weights:[Infinity]},{columns:1,weights:[0]}])assert.throws(()=>validateGridGeometry(invalid));
const state=captureChartLayout({marketMode:'web3',symbol:'SOL',venue:'币安',period:'1时',chartType:'蜡烛图',paneCount:2,paneGeometry:{columns:2,weights:[4,1]},paneSync:[],studies:[],paneSymbols:[],panePeriods:[],paneStudies:[]});
assert.deepEqual(validateChartLayout(JSON.parse(JSON.stringify(state))).paneGeometry,{columns:2,weights:[4,1]});
console.log('Grid geometry: weighted columns, single pane clamp, invalid input and layout roundtrip passed');
const {resizeGridBoundary}=await import('../src/chart-grid-geometry.js');
const equal={columns:3,weights:[1,1,1]};
const moved=resizeGridBoundary(equal,0,.5);
assert.deepEqual(moved.weights,[1.5,.5,1]);
assert.deepEqual(equal.weights,[1,1,1]);
assert.deepEqual(resizeGridBoundary(equal,0,100).weights,[1.75,.25,1]);
assert.throws(()=>resizeGridBoundary(equal,2,1));
assert.throws(()=>resizeGridBoundary(equal,0,NaN));
const {gridRows,resizeGridRowBoundary}=await import('../src/chart-grid-geometry.js');
const rowMoved=resizeGridRowBoundary({columns:2,weights:[1,1]},4,0,.5);
assert.deepEqual(rowMoved.rowWeights,[1.5,.5]);
assert.equal(gridRows(4,rowMoved),'minmax(0,1.5fr) minmax(0,0.5fr)');
assert.deepEqual(resizeGridBoundary(rowMoved,0,.1).rowWeights,[1.5,.5]);
assert.deepEqual(validateChartLayout({...state,paneGeometry:rowMoved}).paneGeometry.rowWeights,[1.5,.5]);
assert.throws(()=>validateGridGeometry({columns:2,weights:[1,1],rowWeights:[0]}));
assert.throws(()=>resizeGridRowBoundary(rowMoved,4,1,1));
console.log('Row geometry: adjacent resize, column preservation, layout persistence and corrupt input passed');
