import assert from 'node:assert/strict';
import {apiRequest, loginBackend, logoutBackend} from '../src/backend-api.js';
import {getBackendSession, getSessionAuthorization, clearBackendSession, setBackendSession} from '../src/backend-session.js';
const original = globalThis.fetch;
const packet = (token, user='tenant-a') => ({session_token:token,expires_at:new Date(Date.now()+60000).toISOString(),user:{user_id:user,role:'viewer'}});
const response = (data,status=200) => ({ok:status<400,status,json:async()=>data});
let request;
try {
  globalThis.fetch=async(url,init)=>{request={url,...init};return response(packet('fixture-session'));};
  await loginBackend('fixture-identity-token');
  assert.equal(request.headers.Authorization,undefined);
  assert.deepEqual(JSON.parse(request.body),{access_token:'fixture-identity-token'});
  assert.equal(getBackendSession().user_id,'tenant-a');
  assert.equal(JSON.stringify(getBackendSession()).includes('fixture-session'),false);
  globalThis.fetch=async(url,init)=>{request={url,...init};return response({ok:true});};
  await apiRequest('/fixture',{body:{user_id:'default-user',value:3},method:'POST'});
  assert.equal(request.headers.Authorization,'Bearer fixture-session');
  assert.equal(JSON.parse(request.body).user_id,'tenant-a');
  let resolveOld;
  globalThis.fetch=()=>new Promise(resolve=>{resolveOld=resolve;});
  const oldRequest=apiRequest('/fixture');
  setBackendSession(packet('new-session','tenant-b'));
  resolveOld(response({},401));
  await assert.rejects(oldRequest,{status:401});
  assert.equal(getBackendSession().user_id,'tenant-b');
  globalThis.fetch=async()=>response({},401);
  await assert.rejects(apiRequest('/fixture'),{status:401});
  assert.equal(getBackendSession(),null);
  assert.throws(()=>setBackendSession({...packet('expired'),expires_at:'2000-01-01T00:00:00Z'}));
  setBackendSession(packet('logout-session'));
  globalThis.fetch=async()=>{throw new Error('offline');};
  await assert.rejects(logoutBackend());
  assert.equal(getSessionAuthorization(),null);
  let finishLogin;
  globalThis.fetch=()=>new Promise(resolve=>{finishLogin=resolve;});
  const pendingLogin=loginBackend('pending-identity');
  await logoutBackend();
  finishLogin(response(packet('late-login')));
  await assert.rejects(pendingLogin,/session_attempt_superseded/);
  assert.equal(getBackendSession(),null);
  globalThis.fetch=async()=>response(null,204);
  assert.equal(await apiRequest('/fixture'),null);
} finally {clearBackendSession();globalThis.fetch=original;}
console.log('Backend session: memory-only identity, authenticated requests, stale-401 race, expiry rejection, logout failure and 204 passed');
