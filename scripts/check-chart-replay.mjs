import {utcDatePresets} from "../src/chart-date-utils.js";
import assert from 'node:assert/strict';
import {emptyReplayLedger,applyReplayTrade,replayProfit,replayStartIndex,replayCloseTime,replayVisibleBars} from '../src/chart-replay.js';
const start=Date.UTC(2026,9,1)/1000;
const bars=Array.from({length:30},(_,index)=>({time:start+index*3600,open:100,high:110,low:90,close:100+index,volume:1}));
assert.equal(replayStartIndex(bars,'数据起点'),14);
assert.equal(replayStartIndex(bars,'2026-10-01T15:00'),15);
assert.throws(()=>replayStartIndex(bars,'2025-01-01T00:00'));
const end=replayCloseTime(bars[14],'1时');assert.equal(replayVisibleBars(bars,end,'1时').length,15);
const fourHour=[{...bars[12],time:start+12*3600}];assert.equal(replayVisibleBars(fourHour,start+15*3600,'4时').length,0);assert.equal(replayVisibleBars(fourHour,start+16*3600,'4时').length,1);
assert.equal(replayVisibleBars(bars,null,'1时').length,0);
let ledger=emptyReplayLedger();const original=ledger;
ledger=applyReplayTrade(ledger,{side:'买入',price:100,time:start,quantity:1});assert.equal(original.quantity,0);
ledger=applyReplayTrade(ledger,{side:'买入',price:120,time:start+3600,quantity:1});assert.equal(ledger.average,110);
ledger=applyReplayTrade(ledger,{side:'卖出',price:130,time:start+7200,quantity:1});assert.equal(ledger.realized,20);assert.deepEqual(replayProfit(ledger,125),{realized:20,unrealized:15,total:35});
assert.throws(()=>applyReplayTrade(ledger,{side:'卖出',price:130,time:start+7200,quantity:2}));
ledger=applyReplayTrade(ledger,{side:'卖出',price:100,time:start+7200,quantity:1});assert.equal(ledger.quantity,0);assert.equal(ledger.realized,10);assert.equal(ledger.average,0);
assert.deepEqual(utcDatePresets(Date.UTC(2026,0,3)).近7天,['2025-12-28','2026-01-03']);
assert.deepEqual(utcDatePresets(Date.UTC(2024,2,1)).近7天,['2024-02-24','2024-03-01']);
assert.deepEqual(utcDatePresets(Date.UTC(2026,9,28)).今年,['2026-01-01','2026-10-28']);
console.log('Replay: actual bar/date cursor, cross-timeframe closed bars, immutable cost basis and realized/unrealized PnL checks passed');
