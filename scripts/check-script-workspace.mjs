import assert from "node:assert/strict";
import { checkScriptText, commitScriptStore, parseScriptImport, readScriptBuffer, readScriptStore, SCRIPT_BUFFER_KEY, SCRIPT_STORE_KEY } from "../src/script-drafts.js";
import { filterIndicatorLibrary, INDICATOR_FAVORITES_KEY, readIndicatorFavorites, toggleIndicatorFavorite } from "../src/indicator-library.js";
function memoryStorage() {
  const values = new Map();
  return { fail: false, getItem: key => values.get(key) ?? null, setItem(key, value) { if (this.fail) throw new Error("QuotaExceededError"); values.set(key, value); } };
}
const storage = memoryStorage(), now = "2026-10-27T00:00:00.000Z";
assert.equal(readScriptBuffer(storage), null);
storage.setItem(SCRIPT_BUFFER_KEY, JSON.stringify({ schema: 1, activeId: null, name: "Unsaved", code: "local buffer" }));
assert.equal(readScriptBuffer(storage).code, "local buffer");
storage.setItem(SCRIPT_STORE_KEY, "corrupt permanent store");
assert.throws(() => readScriptStore(storage));
assert.equal(readScriptBuffer(storage).code, "local buffer");
const separate = memoryStorage(); separate.setItem(SCRIPT_BUFFER_KEY, '{"schema":2,"code":"future"}');
assert.throws(() => readScriptBuffer(separate), /未改写/);
assert.equal(separate.getItem(SCRIPT_BUFFER_KEY), '{"schema":2,"code":"future"}');
storage.setItem(SCRIPT_STORE_KEY, JSON.stringify({ schema: 1, revision: 0, selectedId: null, documents: [] }));
let state = readScriptStore(storage);
assert.equal(state.data.revision, 0);
state = commitScriptStore(storage, state.raw, { type: "save", id: null, name: " Test ", code: "// @version=2\nplot(close)" }, { id: "one", now });
assert.equal(state.data.documents[0].name, "Test");
const stale = state.raw;
state = commitScriptStore(storage, state.raw, { type: "save", id: "one", name: "Test", code: "// @version=2\nplot(open)" }, { now });
assert.equal(state.data.documents[0].version, 2);
assert.equal(state.data.documents[0].history[0].code, "// @version=2\nplot(close)");
assert.throws(() => commitScriptStore(storage, stale, { type: "archive", id: "one" }, { now }), /其他页面/);
assert.equal(storage.getItem(SCRIPT_STORE_KEY), state.raw);
state = commitScriptStore(storage, state.raw, { type: "save", id: "one", name: "Test", code: "// @version=2\nplot(open)" }, { now });
assert.equal(state.data.documents[0].version, 2); // No duplicate history for unchanged saves.
state = commitScriptStore(storage, state.raw, { type: "copy", id: "one", name: "Copy", code: "plot(high)" }, { id: "two", now });
assert.equal(state.data.documents[0].id, "two");
assert.equal(state.data.documents[0].history.length, 0);
state = commitScriptStore(storage, state.raw, { type: "restore-version", id: "one", version: 1 }, { now });
const restored = state.data.documents.find(item => item.id === "one");
assert.equal(restored.version, 3);
assert.equal(restored.code, "// @version=2\nplot(close)");
assert.equal(restored.history[1].code, "// @version=2\nplot(open)");
state = commitScriptStore(storage, state.raw, { type: "archive", id: "one" }, { now });
assert.equal(state.data.selectedId, null);
assert.throws(() => commitScriptStore(storage, state.raw, { type: "select", id: "one" }, { now }), /归档/);
state = commitScriptStore(storage, state.raw, { type: "unarchive", id: "one" }, { now });
state = commitScriptStore(storage, state.raw, { type: "select", id: "one" }, { now });
assert.equal(readScriptStore(storage).data.selectedId, "one");
storage.fail = true;
assert.throws(() => commitScriptStore(storage, state.raw, { type: "save", id: "one", name: "Test", code: "unsaved" }, { now }), /Quota/);
assert.equal(storage.getItem(SCRIPT_STORE_KEY), state.raw);
storage.fail = false;
for (const raw of ["bad-json", '{"schema":2}', JSON.stringify({ ...state.data, selectedId: "missing" }), JSON.stringify({ ...state.data, documents: [restored, restored] })]) {
  const corrupt = memoryStorage(); corrupt.setItem(SCRIPT_STORE_KEY, raw);
  assert.throws(() => readScriptStore(corrupt));
  assert.throws(() => commitScriptStore(corrupt, raw, { type: "save", id: null, name: "X", code: "" }, { id: "new", now }));
  assert.equal(corrupt.getItem(SCRIPT_STORE_KEY), raw);
}
const capped = memoryStorage(); let cap = readScriptStore(capped);
cap = commitScriptStore(capped, cap.raw, { type: "save", id: null, name: "Versions", code: "0" }, { id: "cap", now });
for (let i = 1; i <= 50; i++) cap = commitScriptStore(capped, cap.raw, { type: "save", id: "cap", name: "Versions", code: String(i) }, { now });
assert.throws(() => commitScriptStore(capped, cap.raw, { type: "save", id: "cap", name: "Versions", code: "51" }, { now }), /50个版本/);
assert.equal(readScriptStore(capped).data.documents[0].history.length, 50);
assert.deepEqual(parseScriptImport('// @version=2\nplot(close)', 'Sample.aiscript'), { name: "Sample", code: '// @version=2\nplot(close)' });
assert.deepEqual(parseScriptImport(JSON.stringify({ format: "ai-trading-script", version: 1, name: "Imported", code: "sample", id: "untrusted" }), "source.json"), { name: "Imported", code: "sample" });
assert.throws(() => parseScriptImport('{"name":"unknown","code":"x"}', "bad.json"), /格式/);
assert.throws(() => parseScriptImport("x".repeat(100001), "large.txt"), /长度/);
assert.deepEqual(checkScriptText('// @version=2\nplot("[ignored]", close) /* {ignored} */'), []);
assert.deepEqual(checkScriptText("// @version=2\nplot('escaped \\' quote', close)"), []);
assert.ok(checkScriptText('// @version=2\nplot(close').some(item => item.line === 2 && item.column === 5 && item.message.includes("未闭合")));
assert.ok(checkScriptText('// @version=2\nplot("broken\nclose)').some(item => item.message.includes("字符串")));
assert.ok(checkScriptText('// @version=2\n/* broken').some(item => item.message.includes("注释")));
assert.ok(checkScriptText("// comment only").every(item => item.severity === "warning"));
assert.equal(readIndicatorFavorites(storage).length, 0);
toggleIndicatorFavorite(storage, "EMA"); toggleIndicatorFavorite(storage, "MA");
assert.deepEqual(filterIndicatorLibrary({ section: "收藏", category: "技术指标", query: "ema", favorites: readIndicatorFavorites(storage) }).map(item => item[0]), ["EMA"]);
assert.deepEqual(filterIndicatorLibrary({ section: "快捷", studies: ["MA", "EMA"] }).map(item => item[0]), ["EMA", "MA"]);
toggleIndicatorFavorite(storage, "EMA"); assert.deepEqual(readIndicatorFavorites(storage), ["MA"]);
storage.setItem(INDICATOR_FAVORITES_KEY, "broken");
assert.throws(() => toggleIndicatorFavorite(storage, "EMA"), /损坏/);
assert.equal(storage.getItem(INDICATOR_FAVORITES_KEY), "broken");
console.log("Script workspace: persistent save/copy/history/archive/restore, conflict/quota/corruption guards, import, lexical diagnostics and real favorite/category filters passed.");
