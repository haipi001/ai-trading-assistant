import assert from 'node:assert/strict';
import {heikinAshiBars} from '../src/chart-candle-style.js';
const bars=[{time:1700000000,open:10,high:14,low:8,close:12,volume:5},{time:1700003600,open:13,high:16,low:12,close:15,volume:7}];
const result=heikinAshiBars(bars);
assert.deepEqual(result[0],{...bars[0],open:11,close:11});
assert.deepEqual(result[1],{...bars[1],open:11,close:14,low:11});
assert.equal(bars[1].low,12);
assert.deepEqual(heikinAshiBars(bars.slice(0,1)),result.slice(0,1));
assert.deepEqual(heikinAshiBars([]),[]);
console.log('Average candles: recursive open, OHLC mean, synthetic extrema, immutability and no future dependence passed');
const {hlcPlotBars}=await import('../src/chart-candle-style.js');
const gaps=[bars[0],{...bars[1],open:20,high:22,low:19,close:21}];
const hlc=hlcPlotBars(gaps);
assert.equal(hlc[0].open,10);
assert.equal(hlc[1].open,12);assert.equal(hlc[1].low,12);
assert.equal(gaps[1].open,20);assert.equal(gaps[1].low,19);
assert.deepEqual(hlcPlotBars(gaps.slice(0,1)),hlc.slice(0,1));
console.log('Source-derived HLC: previous close body, gap extrema, first candle, immutable raw data passed');
const {chartPriceLineRising,chartReadoutRising}=await import('../src/chart-candle-style.js');
const prices=[{open:190,close:200},{open:100,close:150},{open:100,close:140}];
assert.equal(chartPriceLineRising(prices,'K线图(HLC)'),false);
assert.equal(chartPriceLineRising(prices,'蜡烛图'),true);
assert.equal(chartReadoutRising(prices,1,'K线图(HLC)'),true);
assert.equal(chartReadoutRising(prices,2,'K线图(HLC)'),false);
assert.equal(chartPriceLineRising([{open:10,close:10}],'蜡烛图'),false);
assert.equal(chartReadoutRising([{open:10,close:10}],0,'蜡烛图'),true);
console.log('Source-derived price/readout colors: HLC baseline, early-bar exception and equality passed');
const {candleChangeMetrics}=await import('../src/chart-candle-style.js');
const metrics=candleChangeMetrics(bars,1);assert.equal(metrics.change,3);assert.equal(metrics.percent,25);assert.ok(Math.abs(metrics.amplitude-100/3)<1e-12);
assert.equal(candleChangeMetrics(bars,0),null);
assert.equal(candleChangeMetrics([{close:0},bars[1]],1),null);
assert.equal(candleChangeMetrics([{close:Number.MIN_VALUE},{close:1,high:2,low:1}],1),null);
console.log('Source readout metrics: previous-close change/amplitude, absent baseline, zero and overflow passed');
const {cursorPriceDifference}=await import('../src/chart-candle-style.js');
assert.deepEqual(cursorPriceDifference(105,100),{price:105,change:5,percent:5});
assert.deepEqual(cursorPriceDifference(90,100),{price:90,change:-10,percent:-10});
assert.equal(cursorPriceDifference(1,0),null);
assert.equal(cursorPriceDifference(null,100),null);
console.log('Cursor price difference: actual coordinate price, sign and invalid baseline guards passed');
