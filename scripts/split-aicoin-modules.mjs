import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { parse } from "@babel/parser";
import generator from "@babel/generator";
const generate = generator.default || generator;
const root = path.resolve(process.argv[2] || "reference/aicoin");
const report = JSON.parse(await fs.readFile(path.join(root, "recovery-report.json"), "utf8"));
const requested = process.argv[3] ? new Set(process.argv[3].split(",")) : null;
const previous = requested ? JSON.parse(await fs.readFile(path.join(root, "module-index.json"), "utf8")) : null;
if (requested) for (const selected of requested) if (!previous.modules.some(module => module.path === selected)) throw new Error(`Unknown recorded factory: ${selected}`);
const disk = await fs.statfs(root);
if (disk.bavail * disk.bsize < (requested ? 50 * 1024 ** 2 : 1024 ** 3)) throw new Error("Insufficient free space; use selected factory regeneration or free space first");
const output = path.join(root, "modules");
await fs.mkdir(output, { recursive: true });
const index = { scope: "Webpack factory extraction from recovered code; dependency calls are static candidates, not standalone runnable components.", archive_sha256: report.archive_sha256, modules: [], files: [] };
const hash = source => createHash("sha256").update(source).digest("hex");
const walk = (node, fn) => {
  if (!node || typeof node !== "object") return;
  fn(node);
  for (const [key, value] of Object.entries(node)) {
    if (["loc", "extra", "comments", "tokens"].includes(key)) continue;
    if (Array.isArray(value)) value.forEach(child => walk(child, fn));
    else if (value && typeof value === "object") walk(value, fn);
  }
};
for (const file of report.files.filter(file => file.status === "recovered")) {
  if (requested && !previous.modules.some(module => module.source === file.path && requested.has(module.path))) continue;
  const text = await fs.readFile(path.join(root, "readable", file.path.replace(/\.js$/, ""), "deobfuscated.js"), "utf8");
  if (hash(text) !== file.output_sha256) throw new Error(`Recovery output drift: ${file.path}`);
  const ast = parse(text, { sourceType: "unambiguous", plugins: ["jsx"] });
  const tables = [];
  walk(ast, node => {
    if (node.type === "CallExpression" && node.callee.type === "MemberExpression" && node.callee.property.name === "push") {
      const table = node.arguments[0]?.type === "ArrayExpression" && node.arguments[0].elements[1];
      if (table?.type === "ObjectExpression") tables.push(table);
    }
  });
  if (file.path === "main.js") {
    const candidates = [];
    walk(ast, node => {
      if (node.type === "ObjectExpression" && node.properties.filter(p => p.key?.type === "NumericLiteral" && (p.type === "ObjectMethod" || /FunctionExpression$/.test(p.value?.type || ""))).length > 10) candidates.push(node);
    });
    candidates.sort((a, b) => b.properties.length - a.properties.length);
    if (candidates[0]) tables.push(candidates[0]);
  }
  let count = 0;
  for (const table of new Set(tables)) for (const member of table.properties) {
    if (!member.key || !["NumericLiteral", "StringLiteral"].includes(member.key.type)) continue;
    const factory = member.type === "ObjectMethod" ? { type: "FunctionExpression", id: null, params: member.params, body: member.body, generator: member.generator, async: member.async } : member.value;
    if (!factory || !["FunctionExpression", "ArrowFunctionExpression"].includes(factory.type)) continue;
    const id = String(member.key.value);
    if (!/^\d+$/.test(id)) continue;
    const relative = file.path.replace(/\.js$/, "") + "/" + id + ".js";
    if (requested && !requested.has(relative)) continue;
    const requireName = factory.params[2]?.name;
    const dependencies = new Set();
    walk(factory.body, node => {
      if (requireName && node.type === "CallExpression" && node.callee.type === "Identifier" && node.callee.name === requireName && node.arguments[0]?.type === "NumericLiteral") dependencies.add(node.arguments[0].value);
    });
    const code = "// Recovered Webpack factory; not original authored source.\nexport default " + generate(factory, { comments: true }).code + ";\n";
    if (requested && hash(code) !== previous.modules.find(module => module.path === relative).sha256) throw new Error(`Regenerated bytes differ: ${relative}`);
    await fs.mkdir(path.dirname(path.join(output, relative)), { recursive: true });
    await fs.writeFile(path.join(output, relative), code);
    index.modules.push({ id, source: file.path, path: relative, source_sha256: file.input_sha256, recovered_sha256: file.output_sha256,
      start: member.start, end: member.end, sha256: hash(code), dependencies: [...dependencies].sort((a, b) => a - b) });
    count++;
  }
  index.files.push({ path: file.path, module_count: count });
}
if (!requested) await fs.writeFile(path.join(root, "module-index.json"), JSON.stringify(index, null, 2) + "\n");
if (requested && index.modules.length !== requested.size) throw new Error("Some selected factories were not regenerated");
console.log(JSON.stringify({ files: index.files.length, factories: index.modules.length }));
