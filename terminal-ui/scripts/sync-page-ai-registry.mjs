import {readFile,writeFile} from 'node:fs/promises';
import vm from 'node:vm';
import {pageAIPolicy} from '../integration/page-ai-actions.mjs';
const file=new URL('../integration/registry.js',import.meta.url),source=await readFile(file,'utf8');
const scope={window:{}};vm.runInNewContext(source,scope);
const features=scope.window.TERMINAL_FEATURES.map(feature=>{
 const policy=pageAIPolicy(feature);
 return {...feature,aiActions:policy.actions.map(action=>action.label),aliases:policy.aliases,supportedMarkets:policy.supportedMarkets,dataRequirements:[...new Set(policy.actions.flatMap(action=>action.requiredSources))],aiPolicyVersion:policy.version,aiActionContracts:policy.actions};
});
await writeFile(file,source.slice(0,source.indexOf('window.TERMINAL_FEATURES')).replace(/\/\/ AI contracts generated[^\n]*\n/g,'')+'// AI contracts generated by scripts/sync-page-ai-registry.mjs. Adapter availability is not evidence.\nwindow.TERMINAL_FEATURES = Object.freeze('+JSON.stringify(features,null,2)+');\n');
console.log('Registered per-page AI contracts for '+features.length+' features; no model invoked.');
